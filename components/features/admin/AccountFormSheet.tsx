"use client";

import { useId, useMemo, useState } from "react";
import { AtSign, Save, UserPlus } from "lucide-react";
import type { Staff } from "@/utils/roomsData";
import type { Account } from "@/lib/server/accounts";
import { ResponsiveSheet, SheetActions } from "@/components/app/ResponsiveSheet";
import { Button } from "@/components/ui/button";
import { Field, Select, TextInput } from "@/components/features/Forms";
import { normalizeUsername } from "@/lib/accounts";
import { ROLES, ROLE_LABEL, type Role } from "@/lib/roles";
import { INPUT_ICON } from "@/lib/styles";

export type AccountFormInput = { username: string; displayName: string; role: Role; staffId: number | null };

const ROLE_OPTIONS = ROLES.map((r) => ({ value: r, label: ROLE_LABEL[r] }));

/**
 * Create or edit an account. The username is chosen once (it is the sign-in name);
 * the temporary password is generated by the server and shown after creation.
 * Render with `key={account?.id ?? "new"}`.
 */
export function AccountFormSheet({
  open,
  onOpenChange,
  account,
  staff,
  pending,
  onSubmit,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  account?: Account | null;
  staff: readonly Staff[];
  pending: boolean;
  onSubmit: (input: AccountFormInput) => Promise<boolean>;
}) {
  const id = useId();
  const editing = Boolean(account);
  const [username, setUsername] = useState(account?.username ?? "");
  const [displayName, setDisplayName] = useState(account?.display_name ?? "");
  const [role, setRole] = useState<Role>(account?.role ?? "reception");
  const [staffId, setStaffId] = useState(account?.staff_id ? String(account.staff_id) : "");

  const staffOptions = useMemo(
    () => [{ value: "", label: "Aucun" }, ...[...staff].sort((a, b) => a.full_name.localeCompare(b.full_name, "fr")).map((s) => ({ value: String(s.id), label: s.full_name }))],
    [staff]
  );

  // Linking an employee fills the display name if it is still empty.
  const linkStaff = (value: string) => {
    setStaffId(value);
    const person = staff.find((s) => String(s.id) === value);
    if (person && !displayName.trim()) setDisplayName(person.full_name);
  };

  return (
    <ResponsiveSheet
      open={open}
      onOpenChange={onOpenChange}
      title={editing ? "Modifier le compte" : "Créer un compte"}
      description={editing ? `Compte ${account?.username}. L’identifiant ne change pas.` : "Un mot de passe temporaire sera généré ; la personne le changera à sa première connexion."}
      footer={
        <SheetActions onCancel={() => onOpenChange(false)}>
          <Button
            type="submit"
            form={`${id}-form`}
            variant="primary"
            isLoading={pending}
            loadingText="Enregistrement"
            leftIcon={editing ? <Save className="size-4" aria-hidden /> : <UserPlus className="size-4" aria-hidden />}
            className="justify-center"
          >
            {editing ? "Enregistrer" : "Créer le compte"}
          </Button>
        </SheetActions>
      }
    >
      <form
        id={`${id}-form`}
        className="flex flex-col gap-4"
        onSubmit={async (e) => {
          e.preventDefault();
          await onSubmit({ username: normalizeUsername(username), displayName: displayName.trim(), role, staffId: staffId ? Number(staffId) : null });
        }}
      >
        <Field label="Identifiant" htmlFor={`${id}-username`} hint={editing ? undefined : "Minuscules, chiffres, point ou tiret ; ex. s.martin"}>
          <div className="relative">
            <AtSign className={INPUT_ICON} aria-hidden />
            <TextInput
              id={`${id}-username`}
              required
              readOnly={editing}
              autoComplete="off"
              autoCapitalize="none"
              spellCheck={false}
              placeholder="s.martin"
              value={username}
              onChange={(e) => setUsername(e.target.value.toLowerCase())}
              className="pl-9 read-only:opacity-70"
            />
          </div>
        </Field>
        <Field label="Employé lié" htmlFor={`${id}-staff`} hint="Facultatif">
          <Select id={`${id}-staff`} value={staffId} options={staffOptions} onChange={linkStaff} />
        </Field>
        <Field label="Nom affiché" htmlFor={`${id}-name`}>
          <TextInput id={`${id}-name`} required autoComplete="off" placeholder="ex. Sami Trabelsi" value={displayName} onChange={(e) => setDisplayName(e.target.value)} />
        </Field>
        <Field label="Rôle" htmlFor={`${id}-role`} hint="Détermine l’espace ouvert à la connexion et les actions permises.">
          <Select id={`${id}-role`} value={role} options={ROLE_OPTIONS} onChange={setRole} />
        </Field>
      </form>
    </ResponsiveSheet>
  );
}
